// Icons of the Explore pages + map: ui/pages/explore/icons/*.svg + ui/pages/explore/icons.slint
// (global EIcons). usage: node tools/gen-explore-icons.mjs <path to node_modules/lucide-react>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const lucide = process.argv[2];
const here = path.dirname(url.fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'ui', 'pages', 'explore', 'icons');
const NAMES = [
  'compass', 'map-pin', 'map-pin-off', 'map', 'sparkles', 'chevron-left', 'chevron-right', 'chevron-up', 'chevron-down', 'film',
  'smartphone', 'scan-face', 'gallery-horizontal-end', 'image-play', 'heart', 'calendar-days', 'clapperboard', 'cloud', 'copy',
  'dices', 'globe', 'hard-drive', 'images', 'moon', 'rectangle-horizontal', 'rectangle-vertical', 'square', 'sunset', 'timer',
  'camera', 'history', 'palette', 'play', 'pause', 'presentation', 'shapes', 'arrow-left', 'check', 'check-check', 'crown',
  'grid-3x3', 'volume-2', 'volume-x', 'x', 'layers', 'maximize-2', 'minimize-2', 'minus', 'plus', 'panel-right-close',
  'panel-right-open', 'wifi-off', 'rotate-cw', 'shield-alert', 'map-pinned', 'message-circle', 'refresh-cw', 'scan',
  'triangle-alert', 'expand', 'shrink',
];
fs.mkdirSync(out, { recursive: true });
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const done = [];
for (const name of NAMES) {
  let file = path.join(lucide, 'dist/esm/icons', `${name}.mjs`);
  if (!fs.existsSync(file)) {
    console.error('missing', name);
    continue;
  }
  for (;;) {
    const m = fs.readFileSync(file, 'utf8').match(/export \{ default \} from '\.\/([^']+)'/);
    if (!m) break;
    file = path.join(lucide, 'dist/esm/icons', m[1]);
  }
  const node = (await import(file)).__iconData.node;
  const body = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v === 'currentColor' ? '#000' : v)}"`).join(' ')}/>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`;
  fs.writeFileSync(path.join(out, `${name}.svg`), svg);
  done.push(name);
}
// the mini map / focus pin: a solid body (colorized with the accent) under the white outline
{
  const pin = fs.readFileSync(path.join(out, 'map-pin.svg'), 'utf8');
  fs.writeFileSync(path.join(out, 'pin-solid.svg'), pin.replace('fill="none"', 'fill="#000"').replace(/<circle[^>]*\/>/, ''));
  fs.writeFileSync(path.join(out, 'pin-outline.svg'), pin.replace('stroke-width="2"', 'stroke-width="1.6"'));
  done.push('pin-solid', 'pin-outline');
}
for (const name of ['heart', 'play']) {
  const svg = fs.readFileSync(path.join(out, `${name}.svg`), 'utf8').replace('fill="none"', 'fill="#000"');
  fs.writeFileSync(path.join(out, `${name}-fill.svg`), svg);
  done.push(`${name}-fill`);
}
const slint = [
  '// Generated by tools/gen-explore-icons.mjs (lucide, ISC — see ../../icons/LICENSE-lucide.txt). Colour them with `colorize`.',
  'export global EIcons {',
  ...done.sort().map((n) => `    out property <image> ${n}: @image-url("icons/${n}.svg");`),
  '    // flag-icons (MIT, ui/pages/explore/LICENSE-flag-icons.txt): one atlas, `source-clip-*` picks a flag (src/explore_flags.rs)',
  '    out property <image> flags: @image-url("flags.png");',
  '}',
  '',
];
fs.writeFileSync(path.join(here, '..', 'ui', 'pages', 'explore', 'icons.slint'), slint.join('\n'));
console.log('explore icons:', done.length);
