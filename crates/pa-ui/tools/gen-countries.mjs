// Country names: Intl.DisplayNames (tr, en) of every ISO 3166-1 alpha-2 code → src/explore_countries.rs
// usage: node tools/gen-countries.mjs
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const tr = new Intl.DisplayNames(['tr-TR'], { type: 'region', fallback: 'none' });
const en = new Intl.DisplayNames(['en-US'], { type: 'region', fallback: 'none' });
const rows = [];
for (let a = 65; a <= 90; a++)
  for (let b = 65; b <= 90; b++) {
    const cc = String.fromCharCode(a, b);
    let t, e;
    try {
      t = tr.of(cc);
      e = en.of(cc);
    } catch {
      continue;
    }
    if (!t || !e || t === cc) continue;
    rows.push([cc, t, e]);
  }
const q = (s) => JSON.stringify(s);
const rs = [
  '//! Generated by tools/gen-countries.mjs: `Intl.DisplayNames` region names (tr, en), sorted by code.',
  '',
  `pub(crate) const COUNTRIES: [(&str, &str, &str); ${rows.length}] = [`,
  ...rows.map(([c, t, e]) => `    (${q(c)}, ${q(t)}, ${q(e)}),`),
  '];',
  '',
];
fs.writeFileSync(path.join(here, '..', 'src', 'explore_countries.rs'), rs.join('\n'));
console.log('countries:', rows.length);
