// Country flags atlas: flag-icons (MIT) 4x3 SVGs → ui/pages/explore/flags.png (CELL_W×CELL_H cells,
// COLS per row) + src/explore_flags.rs (code → cell). Emoji flags are not used: femtovg has no colour
// emoji path we can rely on, and Windows has no flag emoji at all.
// usage: node tools/gen-flags.mjs <flag-icons package dir> <path to node_modules/sharp>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { createRequire } from 'node:module';

const [pkg, sharpDir] = process.argv.slice(2);
const sharp = createRequire(import.meta.url)(sharpDir);
const here = path.dirname(url.fileURLToPath(import.meta.url));
const CELL_W = 64;
const CELL_H = 48;
const COLS = 16;
const dir = path.join(pkg, 'flags', '4x3');
const codes = fs
  .readdirSync(dir)
  .filter((f) => /^[a-z]{2}\.svg$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort();
const rows = Math.ceil(codes.length / COLS);
const composites = [];
for (let i = 0; i < codes.length; i++) {
  const png = await sharp(path.join(dir, `${codes[i]}.svg`), { density: 300 }).resize(CELL_W, CELL_H, { fit: 'fill' }).png().toBuffer();
  composites.push({ input: png, left: (i % COLS) * CELL_W, top: Math.floor(i / COLS) * CELL_H });
}
await sharp({ create: { width: COLS * CELL_W, height: rows * CELL_H, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .png({ compressionLevel: 9, palette: false })
  .toFile(path.join(here, '..', 'ui', 'pages', 'explore', 'flags.png'));
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(here, '..', 'ui', 'pages', 'explore', 'LICENSE-flag-icons.txt'));
const rs = [
  '//! Generated by tools/gen-flags.mjs: the cells of ui/pages/explore/flags.png (flag-icons, MIT).',
  '',
  `/// cell width in the atlas (px)`,
  `pub const CELL_W: i32 = ${CELL_W};`,
  `/// cell height in the atlas (px)`,
  `pub const CELL_H: i32 = ${CELL_H};`,
  `const COLS: usize = ${COLS};`,
  `const CODES: [&str; ${codes.length}] = [${codes.map((c) => `"${c}"`).join(', ')}];`,
  '',
  '/// atlas cell (x, y) of a country code (ISO 3166-1 alpha-2, any case)',
  'pub fn cell(cc: &str) -> Option<(i32, i32)> {',
  '    let cc = cc.to_ascii_lowercase();',
  '    let i = CODES.binary_search(&cc.as_str()).ok()?;',
  '    Some(((i % COLS) as i32 * CELL_W, (i / COLS) as i32 * CELL_H))',
  '}',
  '',
];
fs.writeFileSync(path.join(here, '..', 'src', 'explore_flags.rs'), rs.join('\n'));
console.log('flags:', codes.length, 'atlas', COLS * CELL_W, 'x', rows * CELL_H);
