// Generates ui/viewer/icons/*.svg + ui/viewer/icons.slint (global VIcons): the lucide icons of the
// viewer, video player, selection bar, context menu and action dialogs.
// usage: node tools/gen-viewer-icons.mjs <path to node_modules/lucide-react>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const lucide = process.argv[2];
const here = path.dirname(url.fileURLToPath(import.meta.url));
const ui = path.join(here, '..', 'ui', 'viewer');
const out = path.join(ui, 'icons');
const ICONS = [
  'x', 'zoom-in', 'zoom-out', 'maximize', 'minimize', 'info', 'presentation', 'ellipsis-vertical', 'heart', 'heart-off',
  'share-2', 'download', 'square-pen', 'trash-2', 'chevron-left', 'chevron-right', 'play', 'pause', 'volume-2', 'volume-x',
  'repeat', 'gauge', 'camera', 'square-check-big', 'folder-input', 'copy', 'pencil', 'folder-open', 'external-link',
  'layout-grid', 'chevrons-up-down', 'aperture', 'calendar', 'clock', 'file-image', 'hard-drive', 'map-pin', 'map-pin-off',
  'music', 'film', 'maximize-2', 'circle-check', 'check', 'book-image', 'plus', 'upload', 'folder', 'rotate-cw', 'image',
  'clipboard-copy', 'library', 'chevron-down', 'arrow-left',
];
fs.mkdirSync(out, { recursive: true });
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const names = [];
for (const name of ICONS) {
  let file = path.join(lucide, 'dist/esm/icons', `${name}.mjs`);
  for (;;) {
    const m = fs.readFileSync(file, 'utf8').match(/export \{ default \} from '\.\/([^']+)'/);
    if (!m) break;
    file = path.join(lucide, 'dist/esm/icons', m[1]);
  }
  const node = (await import(file)).__iconData.node;
  const body = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v === 'currentColor' ? '#000' : v)}"`).join(' ')}/>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`;
  fs.writeFileSync(path.join(out, `${name}.svg`), svg);
  names.push(name);
  // filled variants (fill-current in the web UI)
  if (['heart', 'play', 'pause'].includes(name)) {
    fs.writeFileSync(path.join(out, `${name}-fill.svg`), svg.replace('fill="none"', 'fill="#000"'));
    names.push(`${name}-fill`);
  }
}
const lines = names.map((n) => `    out property <image> ${n}: @image-url("icons/${n}.svg");`);
fs.writeFileSync(
  path.join(ui, 'icons.slint'),
  `// Generated by tools/gen-viewer-icons.mjs (lucide, ISC — see ../icons/LICENSE-lucide.txt).\nexport global VIcons {\n${lines.join('\n')}\n}\n`,
);
console.log('viewer icons:', names.length);
