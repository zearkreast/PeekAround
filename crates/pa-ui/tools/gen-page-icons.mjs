// Icons of the library / albums / settings / dialog screens: ui/pages/icons/*.svg + ui/pages/icons.slint
// (global PIcons). usage: node tools/gen-page-icons.mjs <path to node_modules/lucide-react>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const lucide = process.argv[2];
const here = path.dirname(url.fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'ui', 'pages', 'icons');
const NAMES = [
  'arrow-right', 'calendar-range', 'cloud', 'copy', 'folder-plus', 'hard-drive', 'pencil', 'smartphone', 'type', 'presentation',
  'clock-3', 'book-image', 'grip-vertical', 'image-off', 'ellipsis', 'trash-2', 'share-2', 'download', 'folder-open', 'scroll-text',
  'power', 'rotate-cw', 'rotate-ccw', 'refresh-cw', 'laptop', 'wifi', 'cpu', 'archive', 'database-backup', 'map-pin-off', 'map-pin',
  'clapperboard', 'search-x', 'search', 'link', 'log-out', 'log-in', 'user', 'key-round', 'cloud-download', 'cloud-upload', 'upload',
  'folder-up', 'file-archive', 'circle-x', 'circle-check', 'circle-alert', 'loader-circle', 'eye-off', 'eye', 'layers', 'house', 'baby',
  'camera', 'mountain', 'plane', 'flower-2', 'paw-print', 'trophy', 'star', 'music', 'film', 'images', 'folder', 'heart', 'palette',
  'sun', 'moon', 'monitor', 'server', 'external-link', 'shield-check', 'ban', 'folder-x', 'send', 'play', 'pause', 'x', 'check',
  'chevron-right', 'chevron-down', 'chevron-left', 'plus', 'info', 'lock', 'layout-dashboard', 'layout-grid', 'triangle-alert',
  'hourglass', 'zap', 'sparkles', 'gauge', 'network', 'keyboard', 'grid-3x3', 'image', 'calendar-days', 'sliders-horizontal',
  'arrow-down-wide-narrow', 'arrow-up-narrow-wide', 'arrow-left', 'list-filter', 'hard-drive-download', 'unplug', 'qr-code',
  'square-check', 'square', 'minus', 'clock', 'timer', 'cloud-off', 'wifi-off', 'arrow-up-down', 'folder-input', 'file-up', 'globe',
];
fs.mkdirSync(out, { recursive: true });
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const done = [];
for (const name of NAMES) {
  let file = path.join(lucide, 'dist/esm/icons', `${name}.mjs`);
  if (!fs.existsSync(file)) {
    console.error('missing', name);
    continue;
  }
  for (;;) {
    const m = fs.readFileSync(file, 'utf8').match(/export \{ default \} from '\.\/([^']+)'/);
    if (!m) break;
    file = path.join(lucide, 'dist/esm/icons', m[1]);
  }
  const node = (await import(file)).__iconData.node;
  const body = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v === 'currentColor' ? '#000' : v)}"`).join(' ')}/>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`;
  fs.writeFileSync(path.join(out, `${name}.svg`), svg);
  done.push(name);
}
for (const name of ['heart', 'star']) {
  const svg = fs.readFileSync(path.join(out, `${name}.svg`), 'utf8').replace('fill="none"', 'fill="#000"');
  fs.writeFileSync(path.join(out, `${name}-fill.svg`), svg);
  done.push(`${name}-fill`);
}
const slint = [
  '// Generated by tools/gen-page-icons.mjs (lucide, ISC — see ../icons/LICENSE-lucide.txt). Colour them with `colorize`.',
  'export global PIcons {',
  ...done.sort().map((n) => `    out property <image> ${n}: @image-url("icons/${n}.svg");`),
  '}',
  '',
];
fs.writeFileSync(path.join(here, '..', 'ui', 'pages', 'icons.slint'), slint.join('\n'));
console.log('page icons:', done.length);
