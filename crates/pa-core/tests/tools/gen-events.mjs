// Capture WebSocket events of the TS server (Node 22 has a global WebSocket).
import fs from 'node:fs';
const [base, out] = process.argv.slice(2);
const events = [];
const ws = new WebSocket(base.replace('http', 'ws') + '/api/events');
ws.onmessage = (m) => events.push(JSON.parse(m.data));
await new Promise((r) => (ws.onopen = r));
const req = (method, url, body) => fetch(base + url, { method, headers: body ? { 'content-type': 'application/json' } : {}, body: body ? JSON.stringify(body) : undefined }).then((r) => r.json());
const all = await req('GET', '/api/browse?libraryId=1&recursive=true&limit=50');
await req('POST', '/api/media/favorite', { ids: [all.items[0].id], favorite: true });
const a = await req('POST', '/api/albums', { name: 'ev' });
await req('POST', `/api/albums/${a.id}/items`, { ids: [all.items[1].id] });
await req('POST', '/api/folders/1/rescan', {});
const vid = all.items.find((i) => i.kind === 'video');
await req('POST', '/api/jobs/video-edit', { sourceId: vid.id, trim: { start: 0, end: 0.5 }, output: { format: 'gif', height: 60, quality: 'low' } });
await req('PATCH', '/api/settings', { showHidden: false });
await new Promise((r) => setTimeout(r, 6000));
ws.close();
fs.writeFileSync(out, JSON.stringify({ type: 'ServerEvent[]', response: events }, null, 1));
console.log(events.length, [...new Set(events.map((e) => e.type))].join(','));
